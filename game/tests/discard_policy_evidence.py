#!/usr/bin/env python3
"""t22 evidence tool: was each seat's discard really the tile it had just drawn?

The frame log alone cannot answer this: `draw` is unicast to the drawer (PROTOCOL.md §5.5), so the
three AI seats' draws are invisible. This tool reconstructs them instead: the wall shuffle is
deterministic (`mahjong_rules.BuildWall(seed)` + `DealTiles`), so with the seed and the public
frame stream (discard_event / action_event) the tile each seat drew on every turn can be recovered
exactly.

Why it matters: the old auto-play policy is `DefaultDiscard` = "discard the tile just drawn"
(mahjong_rules.cc `DefaultDiscard`), so under it *no* seat can ever discard a tile other than the
one it drew. Any counter-example in a real game is therefore hard evidence that a different discard
policy is wired for that seat. Run it before and after the tile-efficiency policy lands:

  * old policy        -> "changed" == 0 for every seat (the negative control);
  * new policy        -> "changed" > 0 for the AI seats (seats 1..3).

Method self-validation: every visible (human) `draw` frame must equal the reconstructed wall tile;
a mismatch aborts with a non-zero exit code, so the evidence can never be silently wrong.

Usage:
  python3 game/tests/discard_policy_evidence.py --seed 17 --log game/tests/artifacts/e2e_log.jsonl
  python3 game/tests/discard_policy_evidence.py --seed 17 --log ... --json
"""

from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
import tempfile
import collections

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SERVER_DIR = os.path.join(REPO_ROOT, "game", "server")
SEAT_COUNT = 4

WALL_DUMP_SOURCE = """// generated by game/tests/discard_policy_evidence.py
#include <cstdio>
#include <cstdlib>
#include "mahjong_rules.h"
int main(int argc, char** argv) {
  if (argc < 2) return 2;
  uint64_t seed = std::strtoull(argv[1], nullptr, 10);
  std::vector<mahjong::Tile> wall = mahjong::BuildWall(seed);
  mahjong::Deal deal = mahjong::DealTiles(wall);
  std::printf("next_index %d remaining %d size %zu\\n", deal.next_index, deal.remaining, wall.size());
  std::printf("draws");
  for (size_t i = static_cast<size_t>(deal.next_index); i < wall.size(); ++i) {
    std::printf(" %s", mahjong::FormatTile(wall[i]).c_str());
  }
  std::printf("\\n");
  return 0;
}
"""


def build_wall_dump() -> str:
    """Compiles the tiny wall dumper once (cached) and returns its path."""
    cached = os.path.join(tempfile.gettempdir(), "mahjong_wall_dump")
    source = os.path.join(tempfile.gettempdir(), "mahjong_wall_dump.cc")
    needs_build = not os.path.isfile(cached)
    if not needs_build:
        needs_build = os.path.getmtime(cached) < os.path.getmtime(os.path.join(SERVER_DIR, "mahjong_rules.cc"))
    if needs_build:
        with open(source, "w", encoding="utf-8") as handle:
            handle.write(WALL_DUMP_SOURCE)
        command = ["c++", "-std=c++23", "-O1", "-I", SERVER_DIR, "-o", cached, source,
                   os.path.join(SERVER_DIR, "mahjong_rules.cc")]
        result = subprocess.run(command, capture_output=True, text=True)
        if result.returncode != 0:
            raise SystemExit(f"cannot compile the wall dumper:\n{result.stderr}")
    return cached


def wall_for_seed(seed: int, wall_dump: str | None) -> tuple[int, list[str]]:
    if wall_dump:
        with open(wall_dump, encoding="utf-8") as handle:
            text = handle.read()
    else:
        result = subprocess.run([build_wall_dump(), str(seed)], capture_output=True, text=True)
        if result.returncode != 0:
            raise SystemExit(f"wall dumper failed: {result.stderr}")
        text = result.stdout
    start, draws = None, None
    for line in text.splitlines():
        parts = line.split()
        if parts and parts[0] == "next_index":
            start = int(parts[1])
        elif parts and parts[0] == "draws":
            draws = parts[1:]
    if start is None or draws is None:
        raise SystemExit("unusable wall dump")
    return start, draws


def replay(start: int, wall: list[str], log_path: str) -> dict:
    """Rebuilds every seat's draws from the deterministic wall + the public frame stream."""
    cursor = start
    previous_seat = None       # last seat that discarded
    claim = None               # (seat, is_kong) claimed since the last discard
    seen_draw = None           # the human's own draw frame, consumed by its discard
    counters = collections.Counter()
    changed = []
    no_draw_record = []
    human_draw_checks = 0
    discards_seen = 0
    for line in open(log_path, encoding="utf-8"):
        entry = json.loads(line)
        frame = entry.get("frame")
        if not frame:
            continue
        kind = frame.get("type")
        if kind == "draw":  # unicast: only the human seat is visible, which validates the method
            drawn = wall[cursor - start]
            if drawn != frame["tile"]:
                raise SystemExit(f"method invalid: wall says {drawn} but frame says {frame['tile']}")
            cursor += 1
            seen_draw = (frame["seat"], drawn)
            human_draw_checks += 1
            continue
        if kind == "action_event":
            claim = (frame["seat"], frame["action"] == "kong")
            continue
        if kind == "game_end":
            break
        if kind != "discard_event":
            continue
        seat, tile = frame["seat"], frame["tile"]
        if seen_draw is not None and seen_draw[0] == seat:
            drew = seen_draw[1]
            seen_draw = None
        elif previous_seat is None:
            drew = None                                   # dealer's first discard: no draw record
        elif claim is None and seat == (previous_seat + 1) % SEAT_COUNT:
            drew = wall[cursor - start]                   # drew, then discarded
            cursor += 1
        elif claim is not None and seat == claim[0]:
            if claim[1]:                                  # kong replacement draw
                drew = wall[cursor - start]
                cursor += 1
            else:
                drew = None                               # discard after a pong/chow: no draw record
        else:
            raise SystemExit(f"unexpected flow: seat {seat} after {previous_seat}, claim={claim}")
        counters[f"seat{seat}_discards"] += 1
        discards_seen += 1
        if drew is None:
            counters[f"seat{seat}_no_draw_record"] += 1
            no_draw_record.append({"seat": seat, "tile": tile})
        elif drew == tile:
            counters[f"seat{seat}_kept_drawn"] += 1
        else:
            counters[f"seat{seat}_changed"] += 1
            changed.append({"seat": seat, "drew": drew, "discarded": tile})
        previous_seat = seat
        claim = None
    return {"counters": dict(counters), "changed": changed, "no_draw_record": no_draw_record,
            "human_draw_checks": human_draw_checks, "discards_seen": discards_seen,
            "wall_cursor_end": cursor}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--seed", type=int, required=True, help="the server's --seed for this game")
    parser.add_argument("--log", required=True, help="frame log written by e2e_full_game.py")
    parser.add_argument("--wall-dump", default=None, help="precomputed wall dump (skips compiling)")
    parser.add_argument("--json", action="store_true", help="machine-readable output")
    args = parser.parse_args()

    start, wall = wall_for_seed(args.seed, args.wall_dump)
    report = replay(start, wall, args.log)
    ai_changed = [item for item in report["changed"] if item["seat"] != 0]
    report.update({"seed": args.seed, "log": args.log, "wall_start_index": start,
                   "ai_changed": ai_changed, "ai_changed_count": len(ai_changed)})
    if args.json:
        print(json.dumps(report, ensure_ascii=False, indent=2))
        return 0

    counters = report["counters"]
    print(f"[evidence] seed={args.seed} log={args.log}")
    print(f"[evidence] 方法自校验：{report['human_draw_checks']} 次本家 draw 帧与牌山重建逐张一致"
          f"（本家以外的 draw 不上行，故用确定牌山重建）")
    for seat in range(SEAT_COUNT):
        print(f"  seat {seat}: 打牌 {counters.get(f'seat{seat}_discards', 0)} = 打刚摸到的 "
              f"{counters.get(f'seat{seat}_kept_drawn', 0)} + **改打手牌 "
              f"{counters.get(f'seat{seat}_changed', 0)}** + 无摸牌记录 "
              f"{counters.get(f'seat{seat}_no_draw_record', 0)}")
    if ai_changed:
        print(f"[evidence] AI 非“打刚摸到的牌”实例 {len(ai_changed)} 个（新弃牌策略生效的硬证据）：")
        for item in ai_changed[:10]:
            print(f"    seat {item['seat']}: 摸到 {item['drew']} 却打出 {item['discarded']}")
    else:
        print("[evidence] AI 非“打刚摸到的牌”实例 0 个 → 与旧策略 DefaultDiscard 的行为一致")
        print("           （若预期新策略已接线，则说明接线未生效或未构建）")
    print(f"[evidence] 无摸牌记录的打牌 {len(report['no_draw_record'])} 次"
          f"（§6.4 确定性回退：此时应打手中最大牌，可另行核对）")
    return 0


if __name__ == "__main__":
    sys.exit(main())
